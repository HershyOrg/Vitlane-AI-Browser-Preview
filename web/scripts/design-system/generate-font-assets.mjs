import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDir, "../..");
const repositoryRoot = path.resolve(webRoot, "..");
const marketingAssets = path.join(repositoryRoot, "marketing/assets");
const fontOutput = path.join(marketingAssets, "fonts");
const write = process.argv.includes("--write");

const assets = [
  {
    source: "node_modules/pretendard/dist/web/static/woff2-subset/Pretendard-Regular.subset.woff2",
    output: "pretendard-regular.woff2",
  },
  {
    source: "node_modules/pretendard/dist/web/static/woff2-subset/Pretendard-SemiBold.subset.woff2",
    output: "pretendard-semibold.woff2",
  },
  {
    source: "node_modules/pretendard/dist/web/static/woff2-subset/Pretendard-Bold.subset.woff2",
    output: "pretendard-bold.woff2",
  },
  {
    source: "node_modules/@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff2",
    output: "ibm-plex-mono-400.woff2",
  },
  {
    source: "node_modules/@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-600-normal.woff2",
    output: "ibm-plex-mono-600.woff2",
  },
];

const fontCSS = `/* Generated by generate-font-assets.mjs. Do not edit directly. */
@font-face {
  font-family: "Pretendard Variable";
  src: url("./fonts/pretendard-regular.woff2") format("woff2");
  font-style: normal;
  font-weight: 400 599;
  font-display: swap;
}

@font-face {
  font-family: "Pretendard Variable";
  src: url("./fonts/pretendard-semibold.woff2") format("woff2");
  font-style: normal;
  font-weight: 600 699;
  font-display: swap;
}

@font-face {
  font-family: "Pretendard Variable";
  src: url("./fonts/pretendard-bold.woff2") format("woff2");
  font-style: normal;
  font-weight: 700 900;
  font-display: swap;
}

@font-face {
  font-family: "IBM Plex Mono";
  src: url("./fonts/ibm-plex-mono-400.woff2") format("woff2");
  font-style: normal;
  font-weight: 400;
  font-display: swap;
}

@font-face {
  font-family: "IBM Plex Mono";
  src: url("./fonts/ibm-plex-mono-600.woff2") format("woff2");
  font-style: normal;
  font-weight: 600;
  font-display: swap;
}
`;

if (write) {
  await fs.mkdir(fontOutput, { recursive: true });
}

for (const asset of assets) {
  const sourcePath = path.join(webRoot, asset.source);
  const outputPath = path.join(fontOutput, asset.output);
  const expected = await fs.readFile(sourcePath);
  if (write) {
    await fs.writeFile(outputPath, expected);
    continue;
  }
  const actual = await fs.readFile(outputPath).catch(() => null);
  if (!actual || !actual.equals(expected)) {
    throw new Error(
      `../marketing/assets/fonts/${asset.output} is stale; run npm run design:fonts`,
    );
  }
}

const cssPath = path.join(marketingAssets, "fonts.css");
if (write) {
  await fs.writeFile(cssPath, fontCSS);
} else {
  const actual = await fs.readFile(cssPath, "utf8").catch(() => null);
  if (actual !== fontCSS) {
    throw new Error(
      "../marketing/assets/fonts.css is stale; run npm run design:fonts",
    );
  }
}

process.stdout.write(
  `${write ? "generated" : "verified"} Marketing self-hosted font assets\n`,
);
