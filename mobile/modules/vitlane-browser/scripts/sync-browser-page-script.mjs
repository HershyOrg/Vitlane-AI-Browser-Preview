import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(resolve(root, 'scripts/browser-page-agent.js'), 'utf8').replace(/\r\n/g, '\n');
const encoded = Buffer.from(source).toString('base64');
const pieces = encoded.match(/.{1,8000}/g) || [''];
const destination = resolve(root, 'android/src/main/java/com/vitlane/browser/BrowserPageScript.java');
const java = `// Generated by scripts/sync-browser-page-script.mjs. Edit scripts/browser-page-agent.js.
package com.vitlane.browser;

import android.util.Base64;
import java.nio.charset.StandardCharsets;
import org.json.JSONObject;

/** Page-world DOM adapter. Native code owns navigation, approvals and API credentials. */
public final class BrowserPageScript {
    private static final String SOURCE = new String(Base64.decode(
            new StringBuilder(${encoded.length})
${pieces.map(piece => '                    .append(' + JSON.stringify(piece) + ')').join('\n')}
                    .toString(), Base64.DEFAULT), StandardCharsets.UTF_8);

    private BrowserPageScript() {}

    public static String observe() {
        return "(" + SOURCE + ").observe()";
    }

    public static String action(JSONObject action, String expectedUrl) {
        return "(" + SOURCE + ").action(" + action.toString() + ","
                + JSONObject.quote(expectedUrl == null ? "" : expectedUrl) + ")";
    }
}
`;
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replace(/\r\n/g, '\n') !== java) throw new Error('BrowserPageScript.java is stale');
} else {
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, java);
}
